#[cfg(test)]
mod tests {
    use super::*;
    use effectcraft_engine::prefs::{Item, Kind};
    use std::collections::BTreeSet;

    #[test]
    fn german_rows_are_unique_and_preserve_values_and_formatting() {
        let mut keys = BTreeSet::new();
        for (en, de) in UI {
            assert!(keys.insert(en), "duplicate German UI source: {en}");
            assert!(!de.is_empty(), "empty German row: {en}");
            assert_eq!(en.matches("{}").count(), de.matches("{}").count(), "{en}: {de}");
            assert_eq!(en.matches('\n').count(), de.matches('\n').count(), "line breaks: {en}");
            assert_eq!(en.starts_with(' '), de.starts_with(' '), "leading space: {en}");
            assert_eq!(en.ends_with(' '), de.ends_with(' '), "trailing space: {en}");
        }
        for (_, en, de) in MENU {
            assert_eq!(en.contains("..."), de.contains("..."), "dialog ellipsis: {en}");
        }
    }

    #[test]
    fn german_covers_the_panel_catalog_and_the_preferences_schema() {
        let has = |source: &str| UI.iter().any(|(en, _)| *en == source);
        // The panel catalog's existing contract continues to apply to German.
        for (source, _) in super::super::ui::SIMPLIFIED_CHINESE {
            assert!(has(source), "missing German panel row: {source}");
        }
        for panel in crate::dock::PanelKind::ALL {
            assert!(has(panel.title()), "missing German panel title: {}", panel.title());
        }
        for page in effectcraft_engine::prefs::pages() {
            assert!(has(page.title), "missing German page: {}", page.title);
            for item in page.items {
                match item {
                    Item::Section(text) | Item::Note(text) => assert!(has(text), "missing German settings text: {text}"),
                    Item::Button { label, .. } => assert!(has(label), "missing German button: {label}"),
                    Item::Setting { key, label, kind, .. } => {
                        assert!(has(label), "missing German setting: {label}");
                        if let Kind::Choice(options) = kind {
                            // Language names are autonyms, and percentages are language-independent.
                            if key != "general.language" && key != "appearance.uiScale" {
                                for (label, _) in options {
                                    if label.chars().any(char::is_alphabetic) {
                                        assert!(has(label), "missing German option: {label}");
                                    }
                                }
                            }
                        }
                    }
                    _ => {}
                }
            }
        }
    }

    #[test]
    fn german_formatting_and_english_fallback_are_safe() {
        let old = super::super::ui::current();
        super::super::ui::set_current("de");
        assert_eq!(super::super::ui::tr_args("Step {} of {}: {}", &[&2, &4, &"Import"]), "Schritt 2 von 4: Import");
        assert_eq!(super::super::ui::tr_args("Layer {}", &[]), "Ebene ");
        assert_eq!(super::super::ui::tr("unknown future label"), "unknown future label");
        assert_eq!(super::super::ui::tr("Type"), "Text");
        assert_eq!(super::super::ui::tr_context("project.column", "Type"), "Typ");
        super::super::ui::set_current("en");
        assert_eq!(super::super::ui::tr("Cancel"), "Cancel");
        assert_eq!(super::super::ui::tr_context("project.column", "Type"), "Type");
        super::super::ui::set_current(old);
    }
}
